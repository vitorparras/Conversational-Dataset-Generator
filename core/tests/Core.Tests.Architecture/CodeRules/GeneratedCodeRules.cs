using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Core.Tests.Architecture.CodeRules;

/// <summary>No production source looks generated to an analyzer, which skips such code: by header comment, by file name or by attribute.</summary>
internal static class GeneratedCodeRules
{
    private static readonly string[] HeaderMarks = ["<auto-generated", "<autogenerated"];
    private static readonly string[] NameSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];
    private static readonly string[] AttributeNames = ["GeneratedCode", "CompilerGenerated"];

    private static readonly string[] AttributeTypes =
    [
        "System.CodeDom.Compiler.GeneratedCodeAttribute",
        "System.Runtime.CompilerServices.CompilerGeneratedAttribute",
    ];

    public static IEnumerable<Violation> CheckSources(IReadOnlyList<SourceFile> files) =>
        files.SelectMany(Header).Concat(files.SelectMany(Name)).Concat(Attributes(files));

    private static IEnumerable<Violation> Header(SourceFile file) =>
        file.Root.GetLeadingTrivia()
            .Where(trivia => trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
            .Where(trivia => Array.Exists(HeaderMarks, mark => trivia.ToString().Contains(mark, StringComparison.OrdinalIgnoreCase)))
            .Select(_ => new Violation(file.Path, 1, "a header comment marks the file as generated code"));

    private static IEnumerable<Violation> Name(SourceFile file) =>
        Array.Exists(NameSuffixes, suffix => file.FileName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
            ? [new Violation(file.Path, 1, "the file name marks it as generated code")]
            : [];

    private static IEnumerable<Violation> Attributes(IReadOnlyList<SourceFile> files)
    {
        var compilation = SourceCompilation.Of(files);
        return files.SelectMany(file => file.Root.DescendantNodes().OfType<AttributeSyntax>()
            .Where(attribute => IsGeneratedMark(compilation.GetSemanticModel(file.Tree), attribute))
            .Select(attribute => new Violation(file.Path, SourceFile.LineOf(attribute), "an attribute marks the code as generated")));
    }

    /// <summary>Bound by what the name means; spelled by its name only when the compilation cannot bind it.</summary>
    private static bool IsGeneratedMark(SemanticModel model, AttributeSyntax attribute)
    {
        var info = model.GetSymbolInfo(attribute);
        var type = (info.Symbol ?? info.CandidateSymbols.FirstOrDefault())?.ContainingType;
        return type is null
            ? Array.Exists(AttributeNames, name => ServiceTypeIndex.SimpleName(attribute.Name) is var spelled && (spelled == name || spelled == name + "Attribute"))
            : Array.Exists(AttributeTypes, name => name == type.ToDisplayString());
    }
}
